# -*- coding: utf-8 -*-
"""隶属与性质 —— 一家厂归谁管、算什么所有制。

志书把这两件事写在同一句话里,它们答的却是两个问题:

* **隶属**:归哪一级主管 —— 部属、省属、市属、区县属、乡镇、归口、双重领导。
  「深圳电子集团公司是深圳市人民政府直接领导的……」说的是这个。
* **性质**:什么所有制 —— 全民、集体、股份制、中外合资、私营。
  《北京工业志·电子志》名录表里那一栏「性质」说的是这个。

两轴分开记,才写得出「北京无线电三厂 · 市属 · 集体企业」。混作一栏,
地图上就没法分别筛。

两样都是**有年份的**:774 厂建厂时是部属,1995 年已归北京市。这里认的是
**志书写作那一年**的状态;哪一年划归了谁,是另一回事,进「机构沿革」
(关系=划归)——那张表本来就为这个立的。

线索几处,可靠程度差得远,故分三等(见 `pick`):

  一等 名录表 —— 表题言明是哪一类,行就在表里,页序错乱也拆不开它俩
  二等 正文明说 —— 「第四机械工业部直属的北京建中机器厂」
  三等 章节标题 —— 最不可靠,见下

代号(国营第797厂)**不入等** —— 它只作旁证,不填这一栏:774 厂的代号一直挂着,
厂却在七十年代下放了北京市。照代号填,填的是建厂那年的事,写在一栏没有年份的
格子里就成了错话。对不上时在备注里说一句,由人去判。

标题为什么最不可靠:转换稿的页序是乱的。《北京工业志·电子志》第四篇 61 个
「节」有 17 个落在任何「章」之前;更糟的是第 796 行往后那一串 ——797 厂、
718 厂、738 厂、751 厂、761 厂、768 厂,整条酒仙桥部属干线—— 排在「第四章
中外合资电子工业企业」底下。照标题往下继承,这六家就成了合资企业。所以标题
只作**候选**:表说了话以表为准,表没说,标题的说法进「待核」等人看。
"""

import re

# ---------------------------------------------------------------- 取值

#: 隶属(主管层级)。写进表里的就这些词,别的一概不写。
AFFIL_VALUES = ["部属", "省属", "市属", "区县属", "乡镇", "归口", "双重领导", "部或省属"]

#: 性质(所有制)。
NATURE_VALUES = ["全民", "集体", "股份制", "中外合资", "私营"]

# 中央各部委。**逐个列出,不用「[一-龥]{2,4}部」那样的泛式** ——
# 泛式会把「厂部」「干部」「内部」都收进来,一栏错的隶属比空着坏。
_MINISTRY = (r"(?:第[一二三四五六七八九十]机械工业部|[一二三四五六七八九十]机部|"
             r"电子工业部|机械电子工业部|信息产业部|邮电部|航空工业部|航天工业部|"
             r"兵器工业部|国防科工委|国家计委|中央|国务院|[一-龥]{2,4}工业部)")
_PROV = r"(?:[一-龥]{2,3}省(?:人民政府|革命委员会|经委)?|省(?:人民政府|经委|电子工业厅))"
_CITY = r"(?:[一-龥]{2,4}市(?:人民政府|革命委员会|经委)?|市(?:人民政府|经委))"
_DIST = r"(?:[一-龥]{2,4}[区县](?:人民政府)?)"

# 「归……管/领导/直属」的那几种说法。「直接领导」是深圳志的措辞。
# **「划归」「下放」「上收」不在其内** —— 那些是有年份的变动,归「机构沿革」。
_UNDER = r"(?:直属|所属|隶属(?:于)?|归属|直接领导|领导下|主管|管理)"

# 主管词与层级词之间不许夹「与及和、」—— 夹了就是并列两类,不是一句话。
# 「直属与中央在京」是两类并作一表,不是「直属于中央」。
_GAP = r"[^,,。;;与及和、]{0,8}"


#: 正文里的说法,按顺序试,先中先算。
AFFIL_RULES = [
    # 双重领导排头一个 ——「实行部、市双重领导」里「部」「市」都在,
    # 让哪一条单独的规则先中都不对。
    (r"部、?\s*市双重领导|双重领导|部市共管", "双重领导"),
    (r"部、\s*省(?:直属|属)|省、\s*部(?:直属|属)", "部或省属"),
    (r"行业归口|归口(?:管理)?", "归口"),
    (_MINISTRY + _GAP + _UNDER, "部属"),
    (_UNDER + _GAP + _MINISTRY, "部属"),
    (r"中央在[一-龥]{1,4}", "部属"),
    (_PROV + _GAP + _UNDER, "省属"),
    (_UNDER + _GAP + _PROV, "省属"),
    (_CITY + _GAP + _UNDER, "市属"),
    (_UNDER + _GAP + _CITY, "市属"),
    (_DIST + _GAP + _UNDER, "区县属"),
    (_UNDER + _GAP + _DIST, "区县属"),
    (r"乡镇企业|社队企业", "乡镇"),
]

NATURE_RULES = [
    (r"中外合资|合资经营|三资企业", "中外合资"),
    (r"股份(?:制|有限)", "股份制"),
    (r"集体(?:所有制)?(?:企业)?", "集体"),
    (r"全民(?:所有制)?(?:企业)?|国营|国有", "全民"),
    (r"私营|个体户?", "私营"),
]

# ---- 主管单位的名字

# 有名有姓的主管机关:省市区的政府、各级工业局厅、总公司。
# 「隶属」只说到层级(部属 / 市属),说不出是**哪一个**部、哪一个局 ——
# 那一栏另记,两栏合起来才是一句完整的话:「市属 · 北京市电子工业办公室」。
# 地名那一截不许含连接词 —— 不排除的话,「团公司是深圳市人民政府」会整条
# 被认成机关名(「[一-龥]{2,6}市」往左贪到哪儿算哪儿)。跟 place.py 那边
# 认市名撞的是同一个坎。
_PLACE_CH = r"(?:(?![是由为在于和与及的了把将从并该本其此又到直隶归所主管领])[一-龥])"
_ORGAN = (_PLACE_CH + r"{2,4}(?:省|市|区|县)"
          r"(?:人民政府|革命委员会|人民委员会|经委|计委|"
          r"[一-龥]{0,6}(?:工业)?(?:局|厅|办公室|总公司))")

#: 按顺序试,先中先算。每条只有一个捕获组,捕的就是那个名字。
BODY_RULES = [
    re.compile(r"(" + _MINISTRY + r")" + _GAP + _UNDER),
    re.compile(_UNDER + _GAP + r"(" + _MINISTRY + r")"),
    re.compile(r"(" + _ORGAN + r")" + _GAP + _UNDER),
    re.compile(_UNDER + _GAP + r"(" + _ORGAN + r")"),
]


def body_of(text):
    """这句话里,主管的是**哪一个**机关。认不出回 ""。

    「第四机械工业部直属的北京建中机器厂」→ 第四机械工业部
    「深圳市人民政府直接领导的……」     → 深圳市人民政府

    认的主管词与 `affil_of` 同一份(`_UNDER`)——「划归」「下放」「上收」
    不在其内:那些是有年份的变动,归「机构沿革」;这一栏说的是志书写作
    那一年归谁管。"""
    s = str(text or "")
    for rx in BODY_RULES:
        m = rx.search(s)
        if m:
            return m.group(1)
    return ""


# ---- 标题(章节名、表题)另一套认法,见 affil_of_head

#: 标题里一个「类」的记号。一条标题里出现几个**不同**的类,就是几类并作一处。
HEAD_TOKENS = [
    (r"中央在[一-龥]{1,4}|中央|部属|部管|[一二三四五六七八九十]机部|"
     r"第[一二三四五六七八九十]机械工业部|电子工业部", "部属"),
    (r"省属|省直属|省管", "省属"),
    # 光一个市名不算 ——「第二十一节北京市调谐器厂」里的「北京市」是厂名的一截,
    # 不是分类。要「市属」「市管」这样明写的词才算。
    (r"市属|市直属|市管|市人民政府|市电子工业(?:局|办公室|总公司)", "市属"),
    (r"[区县]属|[区县]管|城区|郊区", "区县属"),
    (r"归口", "归口"),
    (r"乡镇|社队", "乡镇"),
]

# 光一个「直属」不说直属于谁,自成一类 —— 北京那个「第一章直属电子工业企业」
# 指的是市总公司直属,可字面上看不出来。它跟别的类一同出现,就是并表。
_BARE = re.compile(r"(?<![部省市区县央])直属")

#: 表题里这几个词一出现,整张表跳过 —— 那是产量表、产值表,不是名录。
_NOT_ROSTER = re.compile(r"产量|产值|销售|利润|统计|完成情况|构成")

# 国营七、八字头的三位代号是电子工业口中央厂的编号(774、798、718、797、
# 738、751、761、768、706、707、700、878……)。只作旁证:774 厂建厂时是部属,
# 七十年代下放北京市,代号却一直挂着。
CODE_RE = re.compile(r"国营第?([0-9〇一二三四五六七八九十]{3,4})厂")
_CN_DIGIT = {"〇": "0", "一": "1", "二": "2", "三": "3", "四": "4",
             "五": "5", "六": "6", "七": "7", "八": "8", "九": "9"}


# 转换稿里的表是一整块 HTML,表题另起一行 —— 对抽取器来说这些都是「正文」。
# 不躲开,北京第一无线电器材厂就会从隔壁那张「表4-2 行业归口……名录」的
# 表题上认出一个「归口」来 —— 那是别人家的表题。
_MARKUP = re.compile(r"[<>]|^\s*(?:附?表)\s?[0-9〇一二三四五六七八九十]")


def is_prose(s):
    """这一行是正文,还是表格、表题一类的标记?"""
    return not _MARKUP.search(str(s or ""))


def _match(text, rules):
    s = str(text or "")
    for rx, val in rules:
        m = re.search(rx, s)
        if m:
            return val, m.group(0)
    return "", ""


def affil_of(text):
    """正文这句话说的是哪一级主管。认不出回 ("", "")。"""
    return _match(text, AFFIL_RULES)


def nature_of(text):
    """这段话说的是什么所有制。认不出回 ("", "")。"""
    return _match(text, NATURE_RULES)


def affil_of_head(text):
    """标题(章节名、表题)说的是哪一类。

    跟正文的认法不同:标题是**分类用的**,一条标题里并列了两类,就一类也不能取。
    「1995年末直属与中央在京电子工业企业名录」并着市直属与部属两类,
    照字面挑一个,63 家全成了部属 —— 里头还有集体企业。

    回 (取值, 原文里中的那一截)。并列两类、或只有一个说不清的「直属」,
    都回 ("", 缘故)。"""
    s = str(text or "")
    # 「部、省直属」是志书自己并的,并且并得明白,单立一类收着
    m = re.search(r"部、\s*省(?:直属|属)|省、\s*部(?:直属|属)", s)
    if m:
        return "部或省属", m.group(0)
    hits = {}
    for rx, val in HEAD_TOKENS:
        m = re.search(rx, s)
        if m:
            hits.setdefault(val, m.group(0))
    if _BARE.search(s):
        hits.setdefault("直属·未言明", "直属")
    if not hits:
        return "", ""
    if len(hits) > 1:
        return "", "并列 " + "、".join(hits)
    val, hit = next(iter(hits.items()))
    if val == "直属·未言明":
        return "", "只说「直属」,没说直属于谁"
    return val, hit


def code_of(text):
    """「国营第797厂」里的 797。中文数字的代号也认(「国营二六一厂」→ 261)。"""
    m = CODE_RE.search(str(text or ""))
    if not m:
        return ""
    raw = m.group(1)
    return "".join(_CN_DIGIT.get(c, c) for c in raw)


def looks_central(code):
    """七、八字头的三位代号 —— **建厂时**多半是部属。只作旁证,不填隶属栏。"""
    c = str(code or "")
    return len(c) == 3 and c[0] in "78"


# ---------------------------------------------------------------- 名录表

# 转换稿里表是一整块 HTML,表题另在前头一个居中的 div 里:
#   <div style="text-align: center;">表4-11995年末直属与中央在京电子工业企业名录</div>
# 「表4-1」与「1995年末」之间没有空格 —— 页码与表题黏着,原样如此。
# 另认单独一行写着表题的稿子(有的转换器不加 div)。
_TITLE_RE = re.compile(
    r'<div[^>]*text-align:\s*center[^>]*>\s*((?:附?表)[^<]{4,80}?)\s*</div>'
    r'|^\s*(?:#{1,6}\s*)?((?:附?表)\s?[0-9〇一二三四五六七八九十\-—－]{1,8}[^\n]{4,80})$',
    re.M)
_TABLE_RE = re.compile(r"<table.*?</table>", re.S)
_ROW_RE = re.compile(r"<tr[^>]*>(.*?)</tr>", re.S)
_CELL_RE = re.compile(r"<t[dh][^>]*>(.*?)</t[dh]>", re.S)
_TAG_RE = re.compile(r"<[^>]+>")

#: 单位名认得下来的收尾字。跟 extract.py 一路,故意收得紧。
_NAME_TAIL = ("厂", "公司", "所", "院")


def _cell(s):
    return re.sub(r"\s+", "", _TAG_RE.sub("", s or ""))


def _bare_name(name):
    return re.sub(r"[（(].*?[)）]", "", name).strip()


def _is_unit(name):
    n = _bare_name(name)
    return len(n) >= 5 and n.endswith(_NAME_TAIL)


def iter_tables(md_text):
    """一张一张地把名录表交出来:(表题, 表头那一行, 余下各行)。

    单独拆出来,是因为不止隶属要用 —— 省志的名录表还有一栏「所在地」,
    认市要用它(见 place.py)。两处各读各的列,走的是同一趟表。"""
    marks = [(m.start(), m.group(1) or m.group(2)) for m in _TITLE_RE.finditer(md_text)]
    for tm in _TABLE_RE.finditer(md_text):
        title = ""
        for pos, txt in marks:
            if pos < tm.start():
                title = txt.strip()
            else:
                break
        rows = _ROW_RE.findall(tm.group(0))
        if not title or not rows:
            continue
        head = [_cell(c) for c in _CELL_RE.findall(rows[0])]
        body = [[_cell(c) for c in _CELL_RE.findall(r)] for r in rows[1:]]
        yield title, head, body


def read_tables(md_text):
    """名录表里的隶属与性质 → {单位正名: {"隶属","性质","据","表"}}。

    表题定这一张的隶属(「行业归口……名录」→ 归口);表里另有「性质」一栏的,
    逐行取。表题认不出隶属的(并了两类的、产量表)照收单位名与性质,
    隶属留空 —— **宁可空着,也不替它挑一个**。"""
    out = {}
    for title, head, body in iter_tables(md_text):
        if _NOT_ROSTER.search(title):
            continue
        t_affil, _ = affil_of_head(title)
        t_nat, _ = nature_of(title)
        nat_col = next((i for i, h in enumerate(head) if "性质" in h), None)
        for cells in body:
            if not cells or not _is_unit(cells[0]):
                continue
            rec = out.setdefault(_bare_name(cells[0]),
                                 {"隶属": "", "性质": "", "据": "", "表": title})
            if t_affil and not rec["隶属"]:
                rec["隶属"], rec["据"] = t_affil, title
            # 行里那一栏「性质」比表题的说法近,以行为准。
            # 认不着就整行找一遍 —— 「续表」的表头常被 OCR 揉坏(「成立 日期 性质」
            # 挤进一格),按表头认列就认错位;而「全民企业」「集体企业」这几个词
            # 在一行里独一无二,整行扫反倒稳当。
            nat = ""
            if nat_col is not None and nat_col < len(cells):
                nat, _ = nature_of(cells[nat_col])
            if not nat:
                for c in cells[1:]:
                    nat, _ = nature_of(c)
                    if nat:
                        break
            if not nat:
                nat = t_nat
            if nat and not rec["性质"]:
                rec["性质"] = nat
    return out


# ---------------------------------------------------------------- 定谳

#: 线索的可靠次序,数越小越可信。代号不在其内 —— 见篇首。
TIER = {"表": 1, "文": 2, "标题": 3}


def pick(cands):
    """几处线索凑一处,定一个说法。

    cands 是 [(来路, 取值, 原文)],来路取 TIER 里那四个词。规矩两条:

    1. **高一等的说了话,低一等的不再算。** 表说归口、标题说合资,以表为准。
    2. **同一等里两说不一,一个也不取。** 与其挑一个,不如空着等人看
       —— 这一栏跟地址一样,错的比空的坏。

    回 (取值, 原文, 来路);两说不一回 ("", 两说各是什么, "两说")。"""
    cands = [(w, v, why) for w, v, why in cands if v]
    if not cands:
        return "", "", ""
    best = min(TIER.get(w, 9) for w, _, _ in cands)
    top = [(w, v, why) for w, v, why in cands if TIER.get(w, 9) == best]
    vals = {v for _, v, _ in top}
    if len(vals) > 1:
        return "", " / ".join("%s说%s" % (w, v) for w, v, _ in top), "两说"
    w, v, why = top[0]
    return v, why, w
